import type { Metadata } from "next";
import Link from "next/link";
import { Suspense, type ReactNode } from "react";
import { notFound } from "next/navigation";
import { CopyButton } from "@/components/CopyButton";
import { getOrgContext } from "@/lib/orgs";
import { readStoredOutput } from "@/lib/ai/recap-schema";
import { createClient } from "@/lib/supabase/server";

export const metadata: Metadata = { title: "Recap · Recapwell" };

type Props = PageProps<"/app/[orgSlug]/recaps/[recapId]">;

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export default function RecapPage({ params }: Props) {
  return (
    <Suspense fallback={<div className="h-96 animate-pulse rounded-2xl bg-white" />}>
      <Recap params={params} />
    </Suspense>
  );
}

async function Recap({ params }: Pick<Props, "params">) {
  const { orgSlug, recapId } = await params;
  if (!UUID.test(recapId)) notFound();
  const ctx = await getOrgContext(orgSlug);
  if (!ctx) notFound();

  // RLS only returns recaps of workspaces the user belongs to; the org filter
  // also keeps a recap from showing up under another workspace's URL.
  const supabase = await createClient();
  const { data: recap } = await supabase
    .from("recaps")
    .select(
      "id, title, input_notes, output, model, input_tokens, output_tokens, created_at, action_items (id, text, owner_name, due_date, done, created_at)",
    )
    .eq("id", recapId)
    .eq("org_id", ctx.org.id)
    .order("created_at", { referencedTable: "action_items" })
    .maybeSingle();
  if (!recap) notFound();

  const output = readStoredOutput(recap.output);
  const email = output.followup_email;

  return (
    <article className="flex flex-col gap-6">
      <div>
        <Link href={`/app/${ctx.org.slug}/recaps`} className="text-sm text-ink-muted hover:text-ink">
          ← All recaps
        </Link>
        <h1 className="mt-2 text-2xl font-semibold">{recap.title}</h1>
        <p className="mt-1 text-sm text-ink-muted">
          {new Date(recap.created_at).toLocaleString("en-GB", { dateStyle: "long", timeStyle: "short" })}
        </p>
      </div>

      <Card title="Summary">
        <p className="leading-relaxed">{output.summary || "No summary."}</p>
      </Card>

      <div className="grid gap-6 md:grid-cols-2">
        <Card title="Decisions">
          <List items={output.decisions} empty="No decisions recorded." />
        </Card>
        <Card title="Open questions">
          <List items={output.open_questions} empty="Nothing left open." />
        </Card>
      </div>

      <Card title={`Action items (${recap.action_items.length})`}>
        {recap.action_items.length > 0 ? (
          <ul className="flex flex-col divide-y divide-line">
            {recap.action_items.map((item) => (
              <li key={item.id} className="flex items-start gap-3 py-3 first:pt-0 last:pb-0">
                <span
                  aria-label={item.done ? "Done" : "Open"}
                  className={`mt-1 size-4 shrink-0 rounded border ${item.done ? "border-brand bg-brand" : "border-line"}`}
                />
                <div className="min-w-0">
                  <p className={item.done ? "text-ink-muted line-through" : ""}>{item.text}</p>
                  <p className="mt-0.5 text-xs text-ink-muted">
                    {item.owner_name ?? "No owner"}
                    {item.due_date &&
                      ` · due ${new Date(item.due_date).toLocaleDateString("en-GB", { day: "numeric", month: "short", timeZone: "UTC" })}`}
                  </p>
                </div>
              </li>
            ))}
          </ul>
        ) : (
          <p className="text-sm text-ink-muted">No action items.</p>
        )}
      </Card>

      {email && (
        <Card
          title="Follow-up email"
          action={<CopyButton text={`Subject: ${email.subject}\n\n${email.body}`} />}
        >
          <p className="text-sm">
            <span className="text-ink-muted">Subject:</span> <strong>{email.subject}</strong>
          </p>
          <p className="mt-3 whitespace-pre-wrap text-sm leading-relaxed">{email.body}</p>
        </Card>
      )}

      <details className="rounded-2xl border border-line bg-white p-5">
        <summary className="cursor-pointer text-sm font-medium">Original notes</summary>
        <pre className="mt-3 whitespace-pre-wrap font-mono text-sm leading-relaxed text-ink-muted">
          {recap.input_notes}
        </pre>
        {recap.model && (
          <p className="mt-4 text-xs text-ink-muted">
            Generated by {recap.model}
            {recap.input_tokens != null &&
              ` · ${recap.input_tokens} input / ${recap.output_tokens ?? 0} output tokens`}
          </p>
        )}
      </details>
    </article>
  );
}

function Card({ title, action, children }: { title: string; action?: ReactNode; children: ReactNode }) {
  return (
    <section className="rounded-2xl border border-line bg-white p-5">
      <div className="mb-3 flex items-center justify-between gap-4">
        <h2 className="font-semibold">{title}</h2>
        {action}
      </div>
      {children}
    </section>
  );
}

function List({ items, empty }: { items: string[]; empty: string }) {
  if (items.length === 0) return <p className="text-sm text-ink-muted">{empty}</p>;
  return (
    <ul className="flex list-disc flex-col gap-1.5 pl-5">
      {items.map((item, i) => (
        <li key={i}>{item}</li>
      ))}
    </ul>
  );
}
